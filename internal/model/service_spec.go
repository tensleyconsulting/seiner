var (
	specIndex = sync.OnceValue(func() map[ServiceType]ServiceSpec {
		m := make(map[ServiceType]ServiceSpec, len(specs))
		for _, s := range specs {
			m[s.Type] = s
		}
		return m
	})
	serviceOrder = sync.OnceValue(func() map[ServiceType]int {
		m := make(map[ServiceType]int, len(specs))
		for i, s := range specs {
			m[s.Type] = i
		}
		return m
	})
	apiIndex = sync.OnceValue(func() map[string]ServiceType {
		m := make(map[string]ServiceType, len(specs))
		for _, s := range specs {
			if s.API == "" {
				continue
			}
			if _, dup := m[s.API]; !dup {
				m[s.API] = s.Type
			}
		}
		return m
	})
)

// Spec returns the registry entry for s.
func Spec(s ServiceType) (ServiceSpec, bool) {
	spec, ok := specIndex()[s]
	return spec, ok
}

// ServiceOrder returns s's registration index and whether s is registered.
func ServiceOrder(s ServiceType) (int, bool) {
	idx, ok := serviceOrder()[s]
	return idx, ok
}

// SortServices orders registered services by registration order and any
// unregistered services after them alphabetically.
func SortServices(svcs []ServiceType) {
	order := serviceOrder()
	slices.SortFunc(svcs, func(a, b ServiceType) int {
		ia, oka := order[a]
		ib, okb := order[b]
		switch {
		case oka && okb:
			return cmp.Compare(ia, ib)
		case oka:
			return -1
		case okb:
			return 1
		default:
			return cmp.Compare(a, b)
		}
	})
}

// Specs returns a copy of the registry in registration order.
func Specs() []ServiceSpec {
	out := make([]ServiceSpec, len(specs))
	copy(out, specs)
	return out
}

// ServiceForAPI maps a Service Usage name onto a known ServiceType. When
// several products share an API, the first in registration order wins.
func ServiceForAPI(api string) (ServiceType, bool) {
	svc, ok := apiIndex()[strings.TrimSpace(api)]
	return svc, ok
}
