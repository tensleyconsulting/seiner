// ServiceSpec is everything the app knows about a product, declared once.
type ServiceSpec struct {
	Type   ServiceType
	Label  string // "Cloud Storage"
	Abbrev string // "GCS" (search term; icon when the renderer draws none)
	// Glyph is the text-mode icon: one emoji that a terminal draws two
	// cells wide (Emoji_Presentation, no variation selector), so rows line
	// up the way they do with Kitty icons. "🪣" for Cloud Storage.
	Glyph      string
	Collection string // "Cloud Storage" (explorer group row)
	// Node names the explorer's product node when it differs from Label
	// ("VPC Networks" for the product whose resources are each a "VPC
	// Network"). Empty uses Label.
	Node string
	// API is the Service Usage name whose enablement this product needs
	// (storage.googleapis.com). Empty for CRM and synthetic nodes.
	API string
	// Gate reports whether List should be skipped when API is disabled in
	// the listed project. False for IAM: bindings come from Resource
	// Manager, and service accounts and custom roles are ClientBased. Org
	// Policy is gated: its adapter calls the Org Policy API, which the
	// listed project must enable.
	Gate bool
	// ClientBased marks a client-based API: Google checks that it is
	// enabled in the caller's quota project, not in the project being
	// listed. Such a product is never gated on the listed project's
	// enabled set, and an API-disabled error naming the quota project is
	// a setup problem. Set it only on evidence: Google does not publish
	// which APIs are client-based.
	ClientBased bool
	// Grouped reports whether resources of this type get a collection row
	// under their CRM node. False for organization, folder, project, and
	// service-usage.
	Grouped bool
	// Group is the product whose explorer node holds this type's collection
	// row (Subnets sit under VPC Networks). Empty puts the collection
	// directly under the CRM node. The group node takes the product's node
	// label and icon, so Group must name a registered spec.
	Group ServiceType
	// GroupOnly marks a product that is only the node other specs' Group
	// names (IAM holds Role Bindings). It lists nothing of its own, so
	// it is not Grouped and has no provider. A GroupOnly product may itself
	// set Group to nest one level under another GroupOnly product (Private
	// Service Connect sits under Network Services).
	GroupOnly bool
	// First lists this product's node first under a CRM node, ahead of
	// its other products (which in turn list ahead of child scopes), so it
	// reads as part of the scope it sits under (IAM, then Organization
	// Policies). First products keep their table order among themselves.
	First bool
	// Scope marks organization, folder, and project.
	Scope bool
	// Bucketed lays this type's resources out in collapsible bucket nodes
	// (model.Buckets), in a collection or a facet, because one list can
	// hold thousands (Workspace users and groups).
	Bucketed bool
	// FolderKey is the Metadata key holding a slash path ("/Sales/EMEA")
	// that files a Bucketed resource in folder nodes before any letter
	// buckets. Empty buckets by name alone.
	FolderKey string
	// Console builds the Cloud Console deep link. nil means the project
	// dashboard.
	Console func(r Resource, s ConsoleScope) string
}

// ConsoleScope is the CRM context precomputed once by Resource.ConsoleURL.
type ConsoleScope struct {
	Kind    string // "organizations", "folders", "projects", or ""
	ID      string // the CRM id
	Project string // set when Kind is "projects"
}

